"""Part registry: turn raw CAD / scans into rest-frame meshes (``data/parts/processed``).

Every part is uniformly scaled so its longest bounding-box side is
``target_max_dim_m`` (default 40 mm, the sensor/slot grid is sized for it), placed in
its most probable stable resting pose with the major axis along the belt (ADR-0007)
and remeshed isotropically for displacement defects.

Output per part ``data/parts/processed/<part_id>/``::

    coarse.npz   rest-frame original tessellation (booleans are applied here)
    fine.npz     rest-frame isotropic remesh (~0.25 mm edges) = nominal template
    part.json    PartSpec
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from ..geometry.mesh_io import LabeledMesh, bounding_radius, focus_point, load_mesh_any, to_rest_frame
from ..geometry.remesh import mesh_stats, remesh_isotropic
from ..schemas.part import PartSpec
from ..utils.io import data_rel, read_json, repo_root, resolve_data_path, write_json
from ..utils.logging import get_logger

log = get_logger(__name__)

#: known sources -> (licence, redistributable)
LICENSES = {
    "fusion360": ("Fusion 360 Gallery Dataset licence (non-commercial research, no redistribution)", False),
    "tless": ("CC BY 4.0 (T-LESS, Hodan et al. 2017)", True),
    "mulsen_ad": ("MIT (MulSen-AD, CVPR 2025)", True),
    "real3d_ad": ("CC BY 4.0 (Real3D-AD, NeurIPS 2023)", True),
    "procedural": ("generated by ISCO (Apache-2.0)", True),
}


from ..utils.io import data_root  # noqa: E402,F401  (re-exported)


def part_dir(part_id: str) -> Path:
    return data_root() / "parts" / "processed" / part_id


def load_part(part_id: str) -> PartSpec:
    return PartSpec.model_validate(read_json(part_dir(part_id) / "part.json"))


def load_part_mesh(part_id: str, which: str = "fine") -> LabeledMesh:
    return LabeledMesh.load(part_dir(part_id) / f"{which}.npz")


def list_parts() -> list[str]:
    root = data_root() / "parts" / "processed"
    return sorted(p.name for p in root.glob("*") if (p / "part.json").exists())


def prepare_part(part_id: str, source_path: str | Path, source: str, target_max_dim_m: float = 0.04,
                 target_edge_m: float = 2.5e-4, stable_pose_index: int = 0, overwrite: bool = False,
                 mesh=None) -> PartSpec:
    out = part_dir(part_id)
    if (out / "part.json").exists() and not overwrite:
        return load_part(part_id)
    tm = mesh if mesh is not None else load_mesh_any(source_path)
    rest, info = to_rest_frame(tm, target_max_dim_m, stable_pose_index=stable_pose_index)
    coarse = LabeledMesh.from_trimesh(rest, meta={"part_id": part_id, "kind": "coarse"})
    fine = remesh_isotropic(coarse, target_edge_m=target_edge_m)
    fine.meta.update({"part_id": part_id, "kind": "fine"})
    out.mkdir(parents=True, exist_ok=True)
    coarse.save(out / "coarse.npz")
    fine.save(out / "fine.npz")
    F = focus_point(fine)
    lic, redist = LICENSES.get(source, ("unknown", False))
    spec = PartSpec(
        part_id=part_id, source=source, license=lic, redistributable=redist,
        source_path=str(source_path), target_max_dim_m=target_max_dim_m,
        mesh_coarse=data_rel(out / "coarse.npz"),
        mesh_fine=data_rel(out / "fine.npz"),
        extents_m=[float(x) for x in rest.extents], focus_m=F.tolist(),
        bounding_radius_m=bounding_radius(fine, F), rest_info=info,
        stats={"coarse": mesh_stats(coarse), "fine": mesh_stats(fine)},
    )
    write_json(out / "part.json", spec.model_dump(mode="json"))
    log.info(f"prepared {part_id}: extents(mm)={np.round(np.array(spec.extents_m) * 1e3, 1).tolist()} "
             f"fine faces={spec.stats['fine']['n_faces']} watertight={spec.stats['fine']['watertight']}")
    return spec


def make_dowel_mesh(diameter_m: float = 8e-3, length_m: float = 35e-3, chamfer_m: float = 0.5e-3, sections: int = 96):
    """Procedural wooden-dowel stand-in for MVTec 3D-AD ``dowel`` (E5b sensor-gap anchor).

    Dimensions are an approximation (to be refined from MVTec point clouds when the
    dataset is available): a cylinder with chamfered ends lying along +X.
    """
    import trimesh

    r = diameter_m / 2.0
    # revolve a profile (radius vs x) with chamfers
    prof = np.array([[0.0, -length_m / 2], [r - chamfer_m, -length_m / 2], [r, -length_m / 2 + chamfer_m],
                     [r, length_m / 2 - chamfer_m], [r - chamfer_m, length_m / 2], [0.0, length_m / 2]])
    m = trimesh.creation.revolve(prof, sections=sections)
    m.apply_transform(trimesh.transformations.rotation_matrix(np.pi / 2, [0, 1, 0]))
    return m


